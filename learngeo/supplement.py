"""Hand-written knowledge that the automated pulls cannot reach.

Two holes in the fetched dataset are structural, not bugs to be fixed with a
better query:

**Wars.** Wikidata's P710 "participant" on a war points at the state that
actually fought, which for anything before about 1950 is a state that no
longer exists: World War II lists Nazi Germany, the Kingdom of Italy and the
Soviet Union, none of which carry an ISO code. So the pull came back with the
Iraq War as the most widely shared conflict in the world (39 countries) and
World War II with two, while the War of 1812 had the United States and nobody
to fight. The table below names the principal belligerents of the major wars
by the modern country that succeeded them.

**People.** Wikidata models a leader as a holder of an office, and the office
usually belongs to the historical state rather than the modern one. Muammar
Gaddafi ran Libya for 42 years and appeared nowhere on Libya's page, because
"Brotherly Leader" is an office of the Libyan Arab Jamahiriya. `FIGURES` names
the two or three people you would expect to see on each country's page.

Both are merged on top of the fetched data at load time, never written into
`countries.json`, so re-running the fetch scripts cannot wipe them.
"""
