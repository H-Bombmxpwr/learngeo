def mark_for(kind, name):
    """The glyph for one chip, or None to fall back to the kind's default."""
    table = {"religion": RELIGION_MARKS, "currency": CURRENCY_MARKS,
             "organization": ORG_MARKS}.get(kind)
    if not table:
        return None
    low = (name or "").lower()
    for needle, glyph in table:
        if needle in low:
            return glyph
    return None


def _landmarks_for(iso):
    raw = LANDMARKS.get(iso)
    if not raw:
        return []
    return [{"name": n.strip(), "wiki": wiki_url(n.strip())}
            for n in raw.split(";") if n.strip()]


# Wikipedia's opening sentence for each curated figure, fetched once by
# `enrich_data.py figures` and cached. The hand-written note says when; this
# says why, in the encyclopaedia's own words. Missing entries just fall back
# to the note.
_SUMMARIES = None


def _summaries():
    """Name -> {summary, wiki, image}, from both caches.

    `figures.json` covers the hand-written historical figures and is
    committed. `bios.json` covers everyone else the dataset knows about --
    sitting leaders, past leaders, famous faces -- and is optional: without it
    a person's card falls back to the structured facts, which is thinner but
    never wrong. Build it with `enrich_data.py bios`.
    """
    global _SUMMARIES
    if _SUMMARIES is None:
        data = os.path.join(os.path.dirname(os.path.dirname(
            os.path.abspath(__file__))), "data")
        merged = {}
        for name in ("bios.json", "figures.json"):
            try:
                with open(os.path.join(data, name), encoding="utf-8") as f:
                    merged.update(json.load(f))
            except (IOError, ValueError):
                pass
        _SUMMARIES = merged
    return _SUMMARIES


def summary_for(name):
    """The Wikipedia opening sentence for one person, if it has been fetched."""
    return _summaries().get(name) or {}


def _people_for(iso):
    out = []
    for entry in FIGURES.get(iso, []):
        name, _, note = entry.partition("|")
        extra = _summaries().get(name) or {}
        out.append({"name": name, "note": note or None,
                    "summary": extra.get("summary"),
                    "image": extra.get("image"),
                    "wiki": extra.get("wiki") or wiki_url(name),
                    "source": "curated"})
    return out


def apply(countries):
    """Merge the curated tables into the loaded dataset, in place."""
    # Wars keep whatever QID the fetched data already used for the same war,
    # so a curated participant lands on the same topic page as a fetched one
    # instead of creating a second node under a slug.
    qid_by_name = {}
    for c in countries.values():
        for w in c.get("wars") or []:
            if w.get("name") and w.get("qid"):
                qid_by_name.setdefault(w["name"].lower(), w["qid"])

    for name, start, end, isos in WARS:
        qid = qid_by_name.get(name.lower())
        for iso in isos.split():
            c = countries.get(iso)
            if not c:
                continue
            wars = c.setdefault("wars", [])
            if any((w.get("name") or "").lower() == name.lower() for w in wars):
                continue
            wars.append({"name": name, "qid": qid, "wiki": wiki_url(name),
                         "start": start, "end": end, "fame": 400,
                         "source": "curated"})

    # Biggest conflicts first, so a fact card shows the wars people have heard
    # of rather than three border skirmishes.
    for c in countries.values():
        if c.get("wars"):
            c["wars"].sort(key=lambda w: -(w.get("fame") or 0))

    for iso, c in countries.items():
        c["key_figures"] = _people_for(iso)
        # The highest point keeps its own row under geography, so it is left
        # out of the landmark list rather than printed twice. It stays a
        # topic of its own either way.
        peaks = {(p.get("name") or "").lower() for p in c.get("highest_point") or []
                 if isinstance(p, dict)}
        c["landmarks"] = [m for m in _landmarks_for(iso)
                          if m["name"].lower() not in peaks]
    return countries
